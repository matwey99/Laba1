#pragma once
#include <string>

// ---------- Complete Binary Tree (префикс команд T), вариант 3 ----------
//
// Дерево хранится в массиве без указателей (неявное представление):
// корень — индекс 0, левый потомок i — 2*i+1, правый потомок i — 2*i+2,
// последний занятый индекс size-1. Такое представление само по себе
// гарантирует, что все уровни, кроме последнего, заполнены полностью,
// а последний уровень заполнен слева направо, то есть дерево полное (complete).
//
// Вставка нового элемента идёт на позицию size — первую свободную позицию
// в порядке обхода по уровням, поэтому структура остаётся полной.

struct CbNode { // один элемент дерева (значение)
    std::string data;
};

struct CbTree {
    std::string* data;
    int size;     // число элементов
    int capacity; // размер блока памяти
};

CbTree* createCbTree();

// Вставка элемента на позицию первого свободного места — O(1) амортизированно.
bool insert(CbTree* tree, const std::string& value);

// Поиск элемента линейным просмотром массива — O(n).
// В дереве полной структуры не задано правило упорядоченности элементов,
// поэтому быстрый поиск возможен только при использовании вспомогательных структур.
bool search(CbTree* tree, const std::string& value);

// Проверка того, что дерево является полным (вместо операции удаления по заданию), O(n).
bool isComplete(CbTree* tree);

// Проверка того, что дерево является полным бинарным (Full) — все узлы имеют 0 или 2 потомка.
bool isFull(CbTree* tree);

int size(CbTree* tree);

// обходы
void inorder(CbTree* tree);   // симметричный: слева, корень, справа
void preorder(CbTree* tree);   // прямой: корень, слева, справа
void postorder(CbTree* tree);  // обратный: слева, справа, корень
void bfs(CbTree* tree);        // в ширину: по уровням

void print(CbTree* tree);
void freeTree(CbTree* tree);